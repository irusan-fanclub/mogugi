// The parser must never panic on a layout surprise: unknown variants are
// rejected with a logged error instead.
func TestParseEntityAppearPacket_VariantIntFlagNoPanic(t *testing.T) {
	defer func() {
		if rec := recover(); rec != nil {
			t.Fatalf("parser panicked: %v", rec)
		}
	}()
	entity, err := ParseEntityAppearPacket(variantAppearMsg())
	if err == nil && entity == nil {
		t.Fatal("nil entity with nil error")
	}
}
